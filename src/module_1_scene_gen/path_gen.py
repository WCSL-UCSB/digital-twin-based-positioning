# =============================================================================
# path_gen.py — Batched Ray-Tracing Path Generation
# =============================================================================
#
# AIM:
#   Performs batched ray tracing using Sionna's PathSolver on a loaded 3D
#   scene to compute multipath propagation data between all TX-RX pairs.
#   For each TX position, it extracts path delays, complex amplitudes,
#   angles of arrival/departure, and path loss. This is the core simulation
#   step that bridges scene geometry to channel-level data.
#
# INPUTS:
#   - Hydra config (from configs/scenarios/*.yaml):
#       * selected_id                    : location key (e.g. "nyc_high_rise")
#       * gps_location_path              : path to GPS locations YAML
#       * scene_xml_path (optional)      : explicit path to scene XML
#       * ray_tracing_params.max_depth   : max ray bounce depth
#       * material_config (optional)     : custom radio material overrides
#   - Scene geometry (XML):
#       default: data/scenes/<selected_id>/scene.xml
#       (generated by run_g2sm.py)
#   - TX/RX layout CSV:
#       data/gps_coordinates/<selected_id>_tx_rx.csv
#       (generated by tx_rx_location_csv_gen.py)
#
# OUTPUTS:
#   - Compressed NumPy file (.npz) saved to:
#       data/path_data/<timestamp>_<scenario_name>_paths.npz
#     Contains: a (complex amplitudes), path_loss_db, tau (delays in ns),
#               theta_t, phi_t (TX angles), theta_r, phi_r (RX angles),
#               metadata (full config snapshot)
#
# CONNECTED DIRECTORIES:
#   - configs/scenarios/       — Hydra config files
#   - data/scenes/             — Input scene geometry (from run_g2sm.py)
#   - data/gps_coordinates/    — Input TX/RX layout CSV (from tx_rx_location_csv_gen.py)
#   - data/path_data/          — Output .npz files (consumed by module_2
#                                filter_and_adjust_paths.py)
#
# USAGE:
#   python path_gen.py --config-name=<scenario>
#   e.g.: python path_gen.py --config-name=test0217
#
# =============================================================================

import os
import csv
import sys
import gc
import numpy as np
import hydra
from omegaconf import DictConfig, OmegaConf
from dotenv import load_dotenv

load_dotenv()

import sionna
from sionna.rt import load_scene, Transmitter, Receiver, PlanarArray, RadioMaterial, PathSolver

def load_devices_from_csv(csv_path):
    """Reads TX/RX positions from a CSV file."""
    devices = []
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Device layout CSV not found at: {csv_path}")

    print(f"Loading devices from: {csv_path}")
    with open(csv_path, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            dev = {
                "name": row['name'],
                "type": row['type'].strip().lower(),
                "pos": [float(row['x']), float(row['y']), float(row['z'])]
            }
            if row.get('look_at_x') and row.get('look_at_y') and row.get('look_at_z'):
                dev['look_at'] = [float(row['look_at_x']), float(row['look_at_y']), float(row['look_at_z'])]
            else:
                dev['look_at'] = None 
            devices.append(dev)
    return devices

def apply_materials(scene, mat_config):
    if isinstance(mat_config, str):
        if not os.path.exists(mat_config):
            print(f"[Warning] Material config file not found: {mat_config}")
            return
        cfg = OmegaConf.load(mat_config)
    else:
        cfg = mat_config

    if 'overrides' not in cfg:
        return

    custom_mats = {}
    for key, props in cfg.overrides.items():
        mat_name = f"custom_{key}"
        new_mat = RadioMaterial(name=mat_name, 
                                relative_permittivity=props['relative_permittivity'], 
                                conductivity=props['conductivity'])
        scene.add(new_mat)
        custom_mats[key] = new_mat

    count = 0
    for obj_name, scene_obj in scene.objects.items():
        for key, new_mat in custom_mats.items():
            if key in obj_name.lower():
                scene_obj.radio_material = new_mat
                count += 1
                break
    print(f"Applied custom materials to {count} objects.")

@hydra.main(version_base=None, config_path="../../configs/scenarios")
def main(cfg: DictConfig):
    OmegaConf.resolve(cfg)

    loc_id = cfg.selected_id
    project_dir = cfg.project_dir
    
    # ==========================================
    # GPS data loading and path setup
    # ==========================================
    gps_path = cfg.gps_location_path
    
    # If the config only provided the directory, automatically append the filename
    if os.path.isdir(gps_path):
        gps_path = os.path.join(gps_path, "gps_locations.yaml")
        
    gps_db = OmegaConf.load(gps_path)
    
    if loc_id in gps_db and 'coordinate_file' in gps_db[loc_id]:
        csv_path = gps_db[loc_id].coordinate_file.replace("${project_dir}", project_dir)
    else:
        print(f"[Info] '{loc_id}' not in GPS database. Using default CSV routing.")
        yaml_dir = os.path.dirname(gps_path)
        csv_path = os.path.join(yaml_dir, f"{loc_id}_tx_rx.csv")

    # ==========================================
    # Load scene and devices
    # ==========================================
    if "scene_xml_path" in cfg:
        raw_path = cfg.scene_xml_path.replace("${project_dir}", project_dir)
        scene_path = os.path.abspath(raw_path)
    else:
        scene_path = os.path.join(project_dir, "data", "scenes", loc_id, "scene.xml")
        
    if not os.path.exists(scene_path):
        raise FileNotFoundError(f"Geometry not found: {scene_path}")
        
    print(f"Loading Scene: {scene_path}")
    scene = load_scene(scene_path)

    devices = load_devices_from_csv(csv_path)
    tx_devices = [d for d in devices if d['type'] == 'tx']
    rx_devices = [d for d in devices if d['type'] == 'rx']

    print("\n--- Device Layout Verification ---")
    print(f"Total Transmitters: {len(tx_devices)}")
    print(f"Total Receivers: {len(rx_devices)}")

    # ==========================================
    # Batched ray tracing
    # ==========================================
    batch_size =  min(cfg.deployment.num_samples, 50)
    num_tx = len(tx_devices)
    num_batches = int(np.ceil(num_tx / batch_size))
    
    print(f"\nTracing {num_tx} paths in {num_batches} batches (Max Depth: {cfg.ray_tracing_params.max_depth})...")
    batched_raw_paths = []

    for batch_idx in range(num_batches):
        start_idx = batch_idx * batch_size
        end_idx = min(start_idx + batch_size, num_tx)
        current_chunk = tx_devices[start_idx:end_idx]
        
        print(f"  -> Batch {batch_idx + 1}/{num_batches}: TX {start_idx + 1} to {end_idx}...")
        
        # reload the scene for each batch to manage memory (Sionna's PathSolver can be memory intensive)
        scene = load_scene(scene_path)
        if 'material_config' in cfg:
            apply_materials(scene, cfg.material_config)

        scene.tx_array = PlanarArray(num_rows=1, num_cols=1, pattern="iso", polarization="V")
        scene.rx_array = PlanarArray(num_rows=1, num_cols=1, pattern="iso", polarization="V")

        for rx_dev in rx_devices:
            scene.add(Receiver(name=rx_dev['name'], position=rx_dev['pos']))
            
        for tx in current_chunk:
            scene.add(Transmitter(name=tx['name'], position=tx['pos']))
            
        # Trace
        solver = PathSolver()
        paths = solver(scene=scene, max_depth=cfg.ray_tracing_params.max_depth, synthetic_array=cfg.ray_tracing_params.synthetic_array)
        
        # Extract native numpy arrays
        # paths.a is a tuple (real, imag) in Sionna 2.0
        # Each has shape (num_rx, num_rx_ant, num_tx, num_tx_ant, num_paths)
        # Squeeze to (num_tx, num_paths) for consistency with other fields
        a_re = paths.a[0].numpy()
        a_im = paths.a[1].numpy()
        a_complex = (a_re + 1j * a_im)[0, 0, :, 0, :]  # (num_tx_batch, num_paths)

        # tau, angles: shape (num_rx, num_tx, num_paths) with synthetic_array
        # [0] selects the single RX -> (num_tx_batch, num_paths)
        batched_raw_paths.append({
            'tau': paths.tau[0].numpy(),
            'a': a_complex,
            'theta_r': paths.theta_r[0].numpy(),
            'phi_r': paths.phi_r[0].numpy(),
            'theta_t': paths.theta_t[0].numpy(),
            'phi_t': paths.phi_t[0].numpy(),
        })
        
        # clear memory before next batch
        del paths
        del solver
        del scene
        gc.collect()

    # ==========================================
    # Merge and extract final path data
    # ==========================================
    print("\nMerging batches and calculating path loss...")
    
    global_max_paths = max([b['tau'].shape[-1] for b in batched_raw_paths])
    
    merged = {k: [] for k in batched_raw_paths[0].keys()}
    for b in batched_raw_paths:
        pad_width = global_max_paths - b['tau'].shape[-1]
        for k in merged.keys():
            val = b[k]
            if pad_width > 0:
                pad_tuple = [(0,0)] * (val.ndim - 1) + [(0, pad_width)]
                if k == 'tau':
                    val = np.pad(val, pad_tuple, constant_values=-1.0)
                elif k == 'a':
                    val = np.pad(val, pad_tuple, constant_values=0j)
                else:
                    val = np.pad(val, pad_tuple, constant_values=0.0)
            merged[k].append(val)

    if len(merged[next(iter(merged))]) == 1:
        final_tensors = {k: merged[k][0] for k in merged.keys()}
    else:
        final_tensors = {k: np.concatenate(merged[k], axis=0) for k in merged.keys()}

    tau = final_tensors['tau'].reshape(-1) * 1e9
    theta_r = final_tensors['theta_r'].reshape(-1)
    phi_r = final_tensors['phi_r'].reshape(-1)
    theta_t = final_tensors['theta_t'].reshape(-1)
    phi_t = final_tensors['phi_t'].reshape(-1)
    
    a_complex = final_tensors['a'].reshape(-1)
    power_lin = np.abs(a_complex)**2
    path_loss_db = -10.0 * np.log10(np.maximum(power_lin, 1e-30))

    # ==========================================
    # Save results
    # ==========================================
    output_dir = os.path.join(project_dir, "data", "path_data")
    os.makedirs(output_dir, exist_ok=True)
    import time
    filename = f"{output_dir}/{time.strftime('%Y%m%d_%H%M%S')}_{cfg.scenario_name}_paths.npz"
    
    print(f"\nSaving cleaned results to {filename}...")
    np.savez(filename, metadata=dict(cfg), a=a_complex, path_loss_db=path_loss_db, 
             tau=tau, theta_t=theta_t, phi_t=phi_t, theta_r=theta_r, phi_r=phi_r)
    print("SUCCESS!")

if __name__ == "__main__":
    main()